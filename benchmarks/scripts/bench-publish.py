#!/usr/bin/env python3
"""bench-publish — regenerate the generated-marker results blocks in
BENCHMARKS.md (and optionally a README teaser) from aggregated.json.

BENCHMARKS.md's Results section and README.md's benchmarks teaser are
GENERATED views of benchmarks/results/aggregated.json: everything between
the marker pairs below is owned by this script. Hand-written prose outside
the markers survives regeneration byte-for-byte; a target file that exists
but has no marker pair gets the block appended, never destroyed (the same
contract as cairn/scripts/cairn-map.py, whose marker mechanics this script
mirrors).

Usage:
    bench-publish.py --in <aggregated.json> [--benchmarks <path>]
                     [--label <caption>] [--readme <path>] [--check]

Behavior:
    1. Validate before touching anything: --in must be an existing file of
       valid JSON with a "cells" object, and every target (--benchmarks,
       default BENCHMARKS.md, plus --readme when given) must already exist
       on disk. This script never invents a target file from nothing; any
       violation dies EXIT_USAGE before any write.
    2. Render the results table from "cells": one row per cell, iterated in
       sorted "task_id::baseline_id" key order (the same order the
       aggregated.json itself uses). Pass renders "n_passed/n_total (P%)".
       Cost renders "$X.XXXX" from cost_median, or the literal "n/a" when
       null (never a fabricated $0.0000). Every task/baseline/category cell
       is escaped via md_cell() before entering the table. An empty "cells"
       renders an explicit pending line instead of a headerless table, so a
       legitimate empty rerun never looks identical to "nothing happened".
    3. Splice the rendered content between the markers, preserving every
       byte outside them exactly. The write happens ONLY when the inner
       content actually changed, so a second identical run is a byte-level
       no-op. Nothing rendered depends on wall-clock time: identical
       --in/--label always regenerate identical output.
    4. --readme <path>: the same splice mechanics against the teaser
       markers, injecting exactly one line (cell count + label +
       BENCHMARKS.md pointer, or the committed pending-state line while
       "cells" is empty).
    5. --check: write nothing; exit 0 when every target's marker content is
       already current, exit 3 with a unified diff on stdout when stale.

Exit codes:
    0 ok    2 usage error    3 stale (--check only)
"""
import argparse
import difflib
import json
import sys
from pathlib import Path

BENCHMARKS_START = "<!-- cairn:generated:benchmarks:start -->"
BENCHMARKS_END = "<!-- cairn:generated:benchmarks:end -->"
TEASER_START = "<!-- cairn:generated:benchmarks-teaser:start -->"
TEASER_END = "<!-- cairn:generated:benchmarks-teaser:end -->"

# Must stay byte-identical to the pending line committed inside README.md's
# teaser markers, so publishing an empty aggregate is a true no-op there.
TEASER_PENDING = ("_Benchmark results: pending first collection. The full "
                  "harness, task corpus and methodology are committed; no "
                  "numbers exist yet._")

EMPTY_CELLS_LINE = "_No cells in aggregated.json — pending first collection._"

EXIT_OK = 0
EXIT_USAGE = 2
EXIT_STALE = 3


def die(msg, code):
    print(f"[bench-publish] error: {msg}", file=sys.stderr)
    sys.exit(code)


def md_cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def split_markers(text, start_marker, end_marker):
    """(prefix incl. start marker, inner, suffix from end marker) or None
    when either marker is missing/misordered (ported from cairn-map.py)."""
    s = text.find(start_marker)
    e = text.find(end_marker)
    if s < 0 or e < 0 or e < s:
        return None
    return (text[:s + len(start_marker)],
            text[s + len(start_marker):e].strip("\n"),
            text[e:])


def render_results(cells, label):
    """The generated content for BENCHMARKS.md's Results markers: a header
    line naming this script and the caption, then the cell table (or the
    explicit pending line when cells is empty)."""
    lines = [f"Generated by bench-publish ({md_cell(label)}): "
             "do not edit between markers", ""]
    if not cells:
        lines.append(EMPTY_CELLS_LINE)
        return "\n".join(lines)
    lines += ["| Task | Baseline | Category | Pass | Cost (median) |",
              "|------|----------|----------|------|---------------|"]
    for key in sorted(cells):
        cell = cells[key] if isinstance(cells[key], dict) else {}
        task_id, _, baseline_id = key.partition("::")
        task_id = cell.get("task_id", task_id)
        baseline_id = cell.get("baseline_id", baseline_id)
        category = cell.get("category")
        n_passed = cell.get("n_passed", 0)
        n_total = cell.get("n_total", 0)
        try:
            pct = round(float(cell.get("pass_rate") or 0.0) * 100)
        except (TypeError, ValueError):
            pct = 0
        cost_median = cell.get("cost_median")
        cost = (f"${cost_median:.4f}"
                if isinstance(cost_median, (int, float))
                and not isinstance(cost_median, bool) else "n/a")
        cat = md_cell(category) if category is not None else "n/a"
        lines.append(f"| {md_cell(task_id)} | {md_cell(baseline_id)} "
                     f"| {cat} | {n_passed}/{n_total} ({pct}%) | {cost} |")
    return "\n".join(lines)


def render_teaser(cells, label):
    """Exactly one line for the README teaser markers."""
    if not cells:
        return TEASER_PENDING
    return (f"**{len(cells)} benchmark cell(s)** measured ({md_cell(label)}); "
            "full methodology, raw data and reproduction in "
            "[BENCHMARKS.md](BENCHMARKS.md).")


def regenerate(old_text, start_marker, end_marker, inner):
    """(changed, new_text_or_None): replace ONLY the inner content between
    the markers, or append the whole block when no marker pair exists —
    every pre-existing byte outside the markers is preserved exactly.
    new_text is None when the content is already current (no write)."""
    parts = split_markers(old_text, start_marker, end_marker)
    old_inner = parts[1] if parts else None
    if old_inner is not None and old_inner == inner:
        return False, None
    block = f"{start_marker}\n{inner}\n{end_marker}"
    if parts is None:
        sep = "" if old_text.endswith("\n") else "\n"
        return True, f"{old_text}{sep}\n{block}\n"
    return True, f"{parts[0]}\n{inner}\n{parts[2]}"


def parse_args(argv):
    parser = argparse.ArgumentParser(
        prog="bench-publish.py",
        description="Regenerate BENCHMARKS.md's generated Results block "
                    "(and optionally a README teaser) from aggregated.json.")
    parser.add_argument("--in", dest="agg", required=True,
                        metavar="AGGREGATED_JSON",
                        help="aggregated.json produced by bench-aggregate.py")
    parser.add_argument("--benchmarks", default="BENCHMARKS.md",
                        metavar="PATH",
                        help="target carrying the benchmarks markers "
                             "(default: BENCHMARKS.md; must already exist)")
    parser.add_argument("--label", default="aggregated results",
                        metavar="CAPTION",
                        help="caption named in the generated header line")
    parser.add_argument("--readme", default=None, metavar="PATH",
                        help="also regenerate this file's teaser markers "
                             "(must already exist)")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 3 with a diff when any "
                             "target is stale, 0 when all are current")
    return parser.parse_args(argv)


def load_cells(path):
    if not path.is_file():
        die(f"--in file not found: {path}", EXIT_USAGE)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        die(f"--in is not valid JSON ({path}): {e}", EXIT_USAGE)
    cells = data.get("cells") if isinstance(data, dict) else None
    if not isinstance(cells, dict):
        die(f'--in JSON has no "cells" object: {path}', EXIT_USAGE)
    return cells


def main():
    args = parse_args(sys.argv[1:])
    cells = load_cells(Path(args.agg))

    targets = [(Path(args.benchmarks), "--benchmarks",
                BENCHMARKS_START, BENCHMARKS_END,
                render_results(cells, args.label))]
    if args.readme is not None:
        targets.append((Path(args.readme), "--readme",
                        TEASER_START, TEASER_END,
                        render_teaser(cells, args.label)))
    for path, flag, _, _, _ in targets:
        if not path.is_file():
            die(f"{flag} target not found: {path} "
                "(bench-publish never creates it)", EXIT_USAGE)

    stale = False
    for path, _, start, end, inner in targets:
        old_text = path.read_text(encoding="utf-8")
        changed, new_text = regenerate(old_text, start, end, inner)
        if args.check:
            if changed:
                stale = True
                print(f"[bench-publish] stale: {path}")
                parts = split_markers(old_text, start, end)
                old_inner = parts[1] if parts else ""
                for line in difflib.unified_diff(
                        old_inner.splitlines(), inner.splitlines(),
                        fromfile="current", tofile="regenerated",
                        lineterm=""):
                    print(line)
            else:
                print(f"[bench-publish] up to date: {path}")
            continue
        if changed:
            path.write_text(new_text, encoding="utf-8")
        print(f"[bench-publish] {'wrote' if changed else 'unchanged'} {path}")
    sys.exit(EXIT_STALE if (args.check and stale) else EXIT_OK)


if __name__ == "__main__":
    main()
